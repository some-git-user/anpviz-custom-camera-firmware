#!/usr/bin/env python3
"""
ANJOY888 dashcam firmware unpack/repack tool
==========================================
Target: firmware_MC500L_V0_AF-RTMP-H5_V3.2.1.2_...bin  (MStar I3 / Linux)

Container layout (all little-endian):
  0x000  magic          "ANJOY888"            (8 bytes)
  0x008  header_crc32   CRC32 of [0x000:0x614) with THIS field zeroed
  0x00C  total_size     total .bin size
  0x010  flags          bit0 = rootfs present, bit1 = 2nd component present
  0x014  kern_off       kernel (uImage, MStar-encrypted) start  = 0x614
  0x018  kern_end       kernel end / gap start
  0x020  platform       "MSTAR_I3_LINUX"
  0x120  rootfs_off     squashfs rootfs offset
  0x124  rootfs_size    squashfs size, rounded up to 0x1000
  0x128  device_name    "MC500L_V0_AF-RTMP-H5_V3.2.1.2_Y_EN_YM500L_V0"
  0x230  comp2_size     second component size (0 here)
  0x614  kernel         uImage (MVX2 encrypted) -- kept byte-for-byte
  ....   zero gap       padding up to rootfs_off
  rootfs_off  squashfs rootfs (xz, block 131072) -- THE WEB UI LIVES HERE
  ....   zero padding   up to total_size

The web UI is <rootfs>/var/www (index.html, js/, css/, html/, ...).
Only the rootfs is modified; the encrypted kernel is copied verbatim.
"""
import os
import re
import struct
import subprocess
import sys
import zlib

HDR_MAGIC = b"ANJOY888"
HDR_LEN = 0x614
ROOTFS_ALIGN = 0x1000
# Original squashfs build timestamp -> reproducible rebuilds.
SOURCE_DATE_EPOCH = 1673337341  # 2023-01-10 08:55:41 UTC

# header field offsets
O_CRC = 0x08
O_TOTAL = 0x0C
O_FLAGS = 0x10
O_KERN_OFF = 0x14
O_KERN_END = 0x18
O_ROOTFS_OFF = 0x120
O_ROOTFS_SIZE = 0x124
O_DEVNAME = 0x128
O_ROOTFS_CRC = 0x228  # CRC32 over the PADDED rootfs region (verified against
                       # v343 + v345 stock: stored == crc32(rootfs[0:size]))
O_KERN_CRC = 0x1C      # kernel checksum (kernel is copied verbatim -> unchanged)
O_COMP2_SIZE = 0x230


def rd(path):
    with open(path, "rb") as f:
        return f.read()


def u32(buf, off):
    return struct.unpack_from("<I", buf, off)[0]


def put_u32(buf, off, val):
    buf[off:off + 4] = struct.pack("<I", val & 0xFFFFFFFF)


def header_crc(header_bytes):
    """CRC32 over the 0x614-byte header with the CRC field itself zeroed."""
    h = bytearray(header_bytes[:HDR_LEN])
    h[O_CRC:O_CRC + 4] = b"\x00\x00\x00\x00"
    return zlib.crc32(bytes(h)) & 0xFFFFFFFF


def devname(header_bytes):
    """Device name string stored at O_DEVNAME (NUL-terminated)."""
    raw = header_bytes[O_DEVNAME:O_DEVNAME + 256]
    return raw.split(b"\x00", 1)[0].decode("ascii", "replace")


def slug_from_devname(name):
    """Camera slug from a device name.

    The device name ends with the marketing model token, e.g.
      MC500L_V0_AF-RTMP-H5_V3.2.1.2_Y_EN_YM500L_V0   -> YM500L
      MCF46D_V4_..._EN_YMF46D_V4_MCF46D_V1_MCF46D_V4  -> YMF46D
    We take the LAST 'YM<alnum>' token, strip a trailing _V<n> revision, and
    uppercase the result. Falls back to the leading model token (M...) if no
    YM-token is present.
    """
    m = re.findall(r"YM[A-Z0-9]+", name)
    if m:
        slug = m[-1]
    else:
        m2 = re.match(r"(M[A-Z0-9]+)", name)
        slug = m2.group(1) if m2 else "UNKNOWN"
    # drop a trailing _V<n> / V<n> revision marker
    slug = re.sub(r"_?V\d+$", "", slug)
    return slug.upper()


def version_from_devname(name):
    """Firmware version like '3.4.5.2' from the device name, or '' if absent."""
    m = re.search(r"V(\d+\.\d+\.\d+(?:\.\d+)?)", name)
    return m.group(1) if m else ""


def describe(bin_path):
    """Print/return (slug, version, device_name) for a firmware .bin."""
    data = rd(bin_path)
    assert data[:8] == HDR_MAGIC, "not an ANJOY888 container"
    dn = devname(data)
    return slug_from_devname(dn), version_from_devname(dn), dn


def squashfs_block_size(sq_bytes):
    """Block size from a squashfs superblock (0 if not a squashfs)."""
    if sq_bytes[:4] != b"hsqs":
        return 0
    bs = struct.unpack_from("<I", sq_bytes, 12)[0]
    if bs >= 4096 and (bs & (bs - 1)) == 0:
        return bs
    return 0


def write_build_info(out_dir, bin_path, block_size, rootfs_off):
    """Persist the per-camera build parameters next to header.bin.

    The block size differs per camera (YM500L=131072, YMF46D=262144) and must
    match the vendor exactly on repack. We record it here so repack does not
    depend on a leftover rootfs.squashfs sitting next to header.bin.
    """
    slug, ver, dn = describe(bin_path)
    info = os.path.join(out_dir, "build.info")
    with open(info, "w") as f:
        f.write("# ANJOY888 build parameters -- generated by extract.sh\n")
        f.write("slug=%s\n" % slug)
        f.write("version=%s\n" % ver)
        f.write("device_name=%s\n" % dn)
        f.write("rootfs_off=%d\n" % rootfs_off)
        f.write("squashfs_block_size=%d\n" % block_size)
    return info


# --------------------------------------------------------------------------
def unpack(bin_path, out_dir):
    data = rd(bin_path)
    assert data[:8] == HDR_MAGIC, "not an ANJOY888 container"
    rootfs_off = u32(data, O_ROOTFS_OFF)
    rootfs_size = u32(data, O_ROOTFS_SIZE)

    os.makedirs(out_dir, exist_ok=True)
    # whole header (0 .. rootfs_off) is kept verbatim for repack
    with open(os.path.join(out_dir, "header.bin"), "wb") as f:
        f.write(data[:rootfs_off])
    # the squashfs image itself (use bytes_used, not the padded size)
    sq = data[rootfs_off:rootfs_off + rootfs_size]
    # trim trailing zero padding to the real squashfs length
    sq_stripped = sq.rstrip(b"\x00")
    # find real end via superblock bytes_used
    if sq[:4] == b"hsqs":
        bytes_used = struct.unpack_from("<q", sq, 40)[0]
        sq = sq[:bytes_used]
    with open(os.path.join(out_dir, "rootfs.squashfs"), "wb") as f:
        f.write(sq)
    # trailing bytes after rootfs (if any)
    tail = data[rootfs_off + rootfs_size:]
    with open(os.path.join(out_dir, "tail.bin"), "wb") as f:
        f.write(tail)

    # record per-camera build params so repack does not depend on the squashfs
    bs = squashfs_block_size(sq)
    write_build_info(out_dir, bin_path, bs, rootfs_off)

    print("header.bin   : %#x bytes (0..%#x)" % (rootfs_off, rootfs_off))
    print("rootfs.sqfs  : %#x bytes @ %#x" % (len(sq), rootfs_off))
    print("tail.bin     : %#x bytes" % len(tail))
    print("extracting web rootfs -> %s/rootfs" % out_dir)
    subprocess.run(["unsquashfs", "-force", "-d",
                   os.path.join(out_dir, "rootfs"),
                   os.path.join(out_dir, "rootfs.squashfs")], check=True)


# --------------------------------------------------------------------------
def repack(rootfs_dir, header_bin, out_bin, rootfs_off=None):
    data_hdr = bytearray(rd(header_bin))
    if rootfs_off is None:
        rootfs_off = len(data_hdr)

    # rebuild squashfs with the SAME params as the original.
    # Pin SOURCE_DATE_EPOCH so our own rebuilds are reproducible
    # (matches the original squashfs build timestamp when unchanged).
    env = dict(os.environ)
    env.setdefault("SOURCE_DATE_EPOCH", str(SOURCE_DATE_EPOCH))
    sq_path = os.path.join(os.path.dirname(rootfs_dir.rstrip("/")),
                          "rootfs_new.squashfs")

    # Auto-detect the original squashfs block size so we match the vendor exactly.
    # (MC500L uses 131072, MCF46D uses 262144 -- hardcoding breaks the match.)
    # Preference order: build.info (tracked, authoritative) > rootfs.squashfs
    # (if still present next to header.bin) > default 131072.
    block_size = 131072
    build_info = os.path.join(os.path.dirname(os.path.abspath(header_bin)),
                             "build.info")
    if os.path.exists(build_info):
        with open(build_info) as _f:
            for _line in _f:
                if _line.startswith("squashfs_block_size="):
                    try:
                        _bs = int(_line.split("=", 1)[1].strip())
                        if _bs >= 4096 and (_bs & (_bs - 1)) == 0:
                            block_size = _bs
                    except ValueError:
                        pass
    orig_sq = os.path.join(os.path.dirname(os.path.abspath(header_bin)),
                          "rootfs.squashfs")
    if block_size == 131072 and os.path.exists(orig_sq):
        _bs = squashfs_block_size(rd(orig_sq)[:32])
        if _bs:
            block_size = _bs
    print("squashfs block size: %d" % block_size)

    subprocess.run([
        "mksquashfs", rootfs_dir, sq_path,
        "-comp", "xz", "-b", str(block_size),
        "-noappend", "-no-xattrs", "-all-root",
    ], check=True, env=env)
    sq = rd(sq_path)

    # pad rootfs to 0x1000
    padded = ((len(sq) + ROOTFS_ALIGN - 1) // ROOTFS_ALIGN) * ROOTFS_ALIGN

    # Optional: round the rootfs up to a whole number of flash ERASE BLOCKS.
    #
    # Why: on YM500L the vendor OTA updater silently REFUSED an image whose
    # rootfs_size was 4 KiB larger than stock (custom1 = 9117696, i.e. not a
    # multiple of the 64 KiB erase size), while an image that landed exactly on
    # a 64 KiB boundary (custom2 = 9043968 = 138 * 65536) flashed fine. Stock
    # itself is NOT 64K-aligned (9113600 = 139.0625 * 64K) because it is
    # written by the factory programmer, not by the OTA path -- so the OTA
    # updater's own alignment/length check is the plausible gate.
    #
    # We cannot prove which rule the updater applies (size-vs-installed, or
    # erase-alignment, or both), so padding to a 64 KiB multiple satisfies BOTH
    # candidate gates at once, as long as the result stays <= the stock size.
    #
    # Read from build.info as `rootfs_pad_multiple=<bytes>` (0/absent = off).
    # The padding is ZERO bytes appended after the squashfs, and the rootfs CRC
    # below is computed over the PADDED bytes, which is exactly the vendor's
    # convention (header@0x228 == crc32(rootfs including padding)), so this
    # does not disturb the checksum. The squashfs superblock's own `bytes_used`
    # still marks the true end of the filesystem, so the kernel mounts the same
    # squashfs and simply ignores the trailing zeros.
    pad_mult = 0
    if os.path.exists(build_info):
        with open(build_info) as _f:
            for _line in _f:
                if _line.startswith("rootfs_pad_multiple="):
                    try:
                        pad_mult = int(_line.split("=", 1)[1].strip())
                    except ValueError:
                        pad_mult = 0
    _env_mult = os.environ.get("ROOTFS_PAD_MULT", "").strip()
    if _env_mult:
        try:
            pad_mult = int(_env_mult)
        except ValueError:
            pass
    if pad_mult and pad_mult >= ROOTFS_ALIGN and (pad_mult & (pad_mult - 1)) == 0:
        padded = ((padded + pad_mult - 1) // pad_mult) * pad_mult
        print("rootfs pad multiple: %d -> padded size %#x (%d x erase blocks)"
              % (pad_mult, padded, padded // pad_mult))

    sq = sq + b"\x00" * (padded - len(sq))

    # original kernel+gap = header .. rootfs_off  (kept verbatim)
    pre = bytes(data_hdr)  # 0 .. rootfs_off (header + kernel + gap)
    total = rootfs_off + len(sq)

    out = bytearray(pre) + bytearray(sq)
    put_u32(out, O_ROOTFS_SIZE, len(sq))
    put_u32(out, O_TOTAL, total)

    # CRITICAL: the updater verifies a per-component CRC32 stored in the header.
    # Without this, any modified rootfs is rejected (silently -- the version
    # page just keeps showing the old build). Verified against v343/v345 stock:
    # header@0x228 == crc32(rootfs_bytes_including_0x1000_padding).
    rootfs_crc = zlib.crc32(bytes(sq)) & 0xFFFFFFFF
    put_u32(out, O_ROOTFS_CRC, rootfs_crc)

    # recompute CRC over the (updated) header with CRC field zeroed
    crc = header_crc(out)
    put_u32(out, O_CRC, crc)

    with open(out_bin, "wb") as f:
        f.write(out)
    print("wrote %s  total=%#x  rootfs_size=%#x  hdr_crc=%#010x  rootfs_crc=%#010x"
          % (out_bin, total, len(sq), crc, rootfs_crc))


# --------------------------------------------------------------------------
if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "help"
    if cmd == "unpack":
        unpack(sys.argv[2], sys.argv[3])
    elif cmd == "repack":
        # repack <rootfs_dir> <header.bin> <out.bin> [rootfs_off]
        off = int(sys.argv[5], 16) if len(sys.argv) > 5 else None
        repack(sys.argv[2], sys.argv[3], sys.argv[4], off)
    elif cmd == "slug":
        # slug <firmware.bin>  -> prints "<slug> <version>" (for shell scripts)
        slug, ver, dn = describe(sys.argv[2])
        print("%s %s" % (slug, ver))
    elif cmd == "devname":
        # devname <firmware.bin> -> prints the raw device name
        print(devname(rd(sys.argv[2])))
    else:
        print(__doc__)
